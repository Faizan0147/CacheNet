import socket
import threading
import time
import argparse

HOST='0.0.0.0' #listen on all interfaces so the client host can connect
PORT=9090
ORIGIN_HOST='127.0.0.1' #192.168.1.10 when deployed on H1
ORIGIN_PORT=8080
DEFAULT_TTL=30 #used when the origin sends no Max-Age header
IDLE_TIMEOUT=15 #seconds to wait for the next client request before sending 408
ORIGIN_TIMEOUT=5 #seconds to wait on the origin before sending 504

cache={} #path -> {"status","reason","headers","body","expires"}
lock=threading.Lock() #protects cache and stats, since every client has its own thread
stats={"hits":0,"misses":0,"bytes_saved":0}


def read_requests(conn,buffer):
    """Return (header_bytes,leftover_buffer) once a full header block is available
       Return (None,buffer) if the peer closed the connection.
       Used for client requests and for origin response headers."""
    while True:
        delimeter_index=buffer.find(b"\r\n\r\n")
        if delimeter_index!=-1:
            header_end=delimeter_index+len(b"\r\n\r\n")
            return bytes(buffer[:header_end]),bytearray(buffer[header_end:])

        new_data=conn.recv(4096)
        if not new_data: #peer closed before sending a full header block
            return None,buffer
        buffer=buffer+new_data


def parse_headers(lines):
    """Turn header lines into a dict with lowercase byte keys"""
    headers={}
    for line in lines:
        if line==b"":
            break
        if b":" not in line:
            raise ValueError("Malformed header line")
        key,value=line.split(b":",1)
        headers[key.strip().lower()]=value.strip()
    return headers


def parse_request(raw):
    """Return {"method","path","version","headers"} or raise ValueError"""
    info=raw.split(b"\r\n")
    if not info or not info[0]:
        raise ValueError("Missing request line")
    parts=info[0].split(b" ")
    if len(parts)!=3:
        raise ValueError("Missing method, path or version from the request line")
    method,path,version=parts
    return {"method":method,"path":path,"version":version,"headers":parse_headers(info[1:])}


def parse_response(raw):
    """Return (status_code,reason,headers) from the origin's header block or raise ValueError"""
    info=raw.split(b"\r\n")
    parts=info[0].split(b" ",2) #reason phrase may contain spaces
    if len(parts)<2 or not parts[1].isdigit():
        raise ValueError("Malformed status line")
    reason=parts[2].decode("latin-1") if len(parts)==3 else ""
    return int(parts[1]),reason,parse_headers(info[1:])


def read_response(sock,buffer,method):
    """Read one full response from the origin: headers, then exactly Content-Length body bytes.
       Return (status,reason,headers,body,leftover_buffer).
       Raise ConnectionError if the origin closes before the response is complete."""
    head,buffer=read_requests(sock,buffer)
    if head is None:
        raise ConnectionError("Origin closed the connection before sending headers")
    status,reason,headers=parse_response(head)

    if method==b"HEAD": #HEAD responses carry Content-Length but no body
        return status,reason,headers,b"",buffer

    length=int(headers.get(b"content-length",b"0"))
    while len(buffer)<length:
        new_data=sock.recv(4096)
        if not new_data:
            raise ConnectionError("Origin closed mid-body (incomplete response)")
        buffer=buffer+new_data
    return status,reason,headers,bytes(buffer[:length]),bytearray(buffer[length:])


def build_response(status_code,reason,content_type,body,extra_headers=None,connection="keep-alive"):
    """Build a response generated by the proxy itself (errors, PURGE replies)"""
    response=[f"HTTP/1.1 {status_code} {reason}",
              f"Content-Type: {content_type}",
              f"Content-Length: {len(body)}",
              f"Connection: {connection}"]
    if extra_headers:
        for name,value in extra_headers:
            response.append(f"{name}: {value}")
    return ("\r\n".join(response)+"\r\n\r\n").encode("utf-8")+body


def build_forwarded(status,reason,headers,body,x_cache,connection):
    """Rebuild an origin response for the client: keep the origin headers,
       replace Connection (hop-by-hop) and add X-Cache"""
    response=[f"HTTP/1.1 {status} {reason}"]
    for name,value in headers.items():
        if name==b"connection":
            continue
        response.append(f"{name.decode('latin-1').title()}: {value.decode('latin-1')}")
    response.append(f"Connection: {connection}")
    response.append(f"X-Cache: {x_cache}")
    return ("\r\n".join(response)+"\r\n\r\n").encode("latin-1")+body


def cache_key(path):
    """Map "/" and "/index.html" to the same entry, like the origin does"""
    return b"/index.html" if path in (b"/",b"") else path


def cache_get(key):
    """Return a fresh entry or None. Expired entries are deleted on lookup."""
    with lock:
        entry=cache.get(key)
        if entry and time.time()>entry["expires"]:
            del cache[key]
            print("Expired:",key.decode("latin-1"))
            return None
        return entry


def cache_put(key,status,reason,headers,body):
    """Store a response for Max-Age seconds (DEFAULT_TTL if missing). Max-Age 0 means do not cache."""
    try:
        ttl=int(headers.get(b"max-age",DEFAULT_TTL))
    except ValueError:
        ttl=DEFAULT_TTL
    if ttl<=0:
        return
    with lock:
        cache[key]={"status":status,"reason":reason,"headers":headers,"body":body,"expires":time.time()+ttl}


def close_origin(origin):
    if origin["sock"]:
        origin["sock"].close()
    origin["sock"]=None
    origin["buf"]=b""


def forward(origin,method,path):
    """Send the request to the origin and return (status,reason,headers,body).
       origin: {"sock","buf"} kept per client thread so the origin connection is reused.
       A reused connection may have gone stale (origin idle-closed it), so retry once on a fresh one."""
    request=(f"{method.decode()} {path.decode('latin-1')} HTTP/1.1\r\n"
             f"Host: {ORIGIN_HOST}:{ORIGIN_PORT}\r\n"
             f"Connection: keep-alive\r\n\r\n").encode("latin-1")

    for _ in range(2): #second pass always uses a fresh connection, so it returns or raises
        reused=origin["sock"] is not None
        if not reused:
            origin["sock"]=socket.create_connection((ORIGIN_HOST,ORIGIN_PORT),timeout=ORIGIN_TIMEOUT)
            origin["buf"]=b""
        try:
            origin["sock"].sendall(request)
            status,reason,headers,body,origin["buf"]=read_response(origin["sock"],origin["buf"],method)
        except ConnectionError:
            close_origin(origin)
            if reused:
                continue #stale keep-alive connection, try again on a new one
            raise
        except Exception:
            close_origin(origin)
            raise

        if reused and status==408: #origin timed out the idle connection before our request
            close_origin(origin)
            continue
        if headers.get(b"connection",b"").lower()==b"close":
            close_origin(origin)
        return status,reason,headers,body


def handle_request(parsed,origin,connection):
    """Return (response_bytes,x_cache,status) for one client request"""
    method=parsed["method"]
    key=cache_key(parsed["path"])

    if method==b"PURGE":
        with lock:
            if key==b"*": #PURGE * clears the whole cache
                cache.clear()
                found=True
            else:
                found=cache.pop(key,None) is not None
        if found:
            return build_response(200,"OK","text/plain",b"Purged",connection=connection),"-",200
        return build_response(404,"Not Found","text/plain",b"Not cached",connection=connection),"-",404

    if method not in (b"GET",b"HEAD"):
        return build_response(405,"Method Not Allowed","text/plain",b"Method Not Allowed",
                              extra_headers=[("Allow","GET, HEAD, PURGE")],connection=connection),"-",405

    entry=cache_get(key)
    if entry:
        body=entry["body"] if method==b"GET" else b"" #HEAD on a cached object: headers only
        with lock:
            stats["hits"]+=1
            stats["bytes_saved"]+=len(body)
        return build_forwarded(entry["status"],entry["reason"],entry["headers"],body,"HIT",connection),"HIT",entry["status"]

    with lock:
        stats["misses"]+=1
    try:
        status,reason,headers,body=forward(origin,method,parsed["path"])
    except socket.timeout:
        return build_response(504,"Gateway Timeout","text/plain",b"Gateway Timeout",connection=connection),"MISS",504
    except (OSError,ValueError) as e: #refused, reset, incomplete or malformed origin response
        print("Origin error:",e)
        return build_response(502,"Bad Gateway","text/plain",b"Bad Gateway",connection=connection),"MISS",502

    if method==b"GET" and status==200: #only full successful GET responses are cached
        cache_put(key,status,reason,headers,body)
    return build_forwarded(status,reason,headers,body,"MISS",connection),"MISS",status


def handle_client(conn,addr):
    """Keep-alive loop for one client. Each client gets its own origin connection."""
    buffer=b""
    origin={"sock":None,"buf":b""}
    conn.settimeout(IDLE_TIMEOUT)
    with conn:
        try:
            while True:
                try:
                    request,buffer=read_requests(conn,buffer)
                except socket.timeout: #client sent nothing for IDLE_TIMEOUT seconds
                    print("Idle timeout:",addr)
                    conn.sendall(build_response(408,"Request Timeout","text/plain",b"Request Timeout",connection="close"))
                    break
                if request is None:
                    print("Client disconnected:",addr)
                    break

                try:
                    parsed=parse_request(request)
                except ValueError as e:
                    print("Bad request:",e)
                    conn.sendall(build_response(400,"Bad Request","text/plain",b"Bad Request"))
                    continue

                close=parsed["headers"].get(b"connection",b"").lower()==b"close" #non-persistent mode
                start=time.perf_counter()
                response,x_cache,status=handle_request(parsed,origin,"close" if close else "keep-alive")
                conn.sendall(response)
                elapsed=(time.perf_counter()-start)*1000
                print(f"{addr[0]}:{addr[1]} {parsed['method'].decode()} {parsed['path'].decode('latin-1')} "
                      f"{x_cache} {status} {elapsed:.2f} ms")
                if close:
                    break
        except (ConnectionResetError,ConnectionAbortedError,BrokenPipeError): #client dropped mid-transfer
            print("Connection lost:",addr)
        finally:
            close_origin(origin)


def main():
    global PORT,ORIGIN_HOST,ORIGIN_PORT,DEFAULT_TTL
    parser=argparse.ArgumentParser(description="CacheNet caching proxy")
    parser.add_argument("--port",type=int,default=PORT)
    parser.add_argument("--origin-host",default=ORIGIN_HOST)
    parser.add_argument("--origin-port",type=int,default=ORIGIN_PORT)
    parser.add_argument("--ttl",type=int,default=DEFAULT_TTL,help="TTL when the origin sends no Max-Age")
    args=parser.parse_args()
    PORT,ORIGIN_HOST,ORIGIN_PORT,DEFAULT_TTL=args.port,args.origin_host,args.origin_port,args.ttl

    with socket.socket(socket.AF_INET,socket.SOCK_STREAM) as server:
        server.setsockopt(socket.SOL_SOCKET,socket.SO_REUSEADDR,1)
        server.bind((HOST,PORT))
        server.listen()
        server.settimeout(1) #wake up every second so Ctrl+C works on Windows
        print(f"Proxy listening on {HOST}:{PORT}, origin {ORIGIN_HOST}:{ORIGIN_PORT}, default TTL {DEFAULT_TTL}s")
        try:
            while True:
                try:
                    conn,addr=server.accept()
                    threading.Thread(target=handle_client,args=(conn,addr),daemon=True).start()
                except socket.timeout:
                    pass #no "continue" here: on Python 3.12/Windows a Ctrl+C landing on it skips the KeyboardInterrupt handler
        except KeyboardInterrupt:
            with lock:
                total=stats["hits"]+stats["misses"]
                ratio=stats["hits"]/total*100 if total else 0
                print(f"\nHits: {stats['hits']}  Misses: {stats['misses']}  Hit ratio: {ratio:.1f}%  "
                      f"Bytes saved: {stats['bytes_saved']}")


if __name__=="__main__":
    main()
